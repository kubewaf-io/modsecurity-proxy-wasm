#!/usr/bin/env python3
"""Embed virtual @-includes for the modsecurity-proxy-wasm Envoy plugin.

Path B catalog only
-------------------
Structured SecRule CRs supply CRS rules at runtime. The wasm embeds:
  - @kubewaf-defaults, @ftw-conf, @demo-conf
  - @crs-data/*.data  (phrase lists for @pmFromFile)

CRS rule confs (@owasp_crs/*.conf, @crs-setup-conf) are intentionally not embedded.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path


def raw_cpp_string(data: str, tag: str) -> str:
    # Always use escaped chunks: CRS/setup files contain ')" sequences and '#' lines.
    return c_escaped_concat(data, tag)


def c_escaped_concat(data: str, tag: str) -> str:
    del tag  # reserved for future named raw strings
    chunk = 12000
    parts = []
    for i in range(0, len(data), chunk):
        piece = data[i : i + chunk]
        esc = (
            piece.replace("\\", "\\\\")
            .replace('"', '\\"')
            .replace("\n", "\\n")
            .replace("\r", "\\r")
            .replace("\t", "\\t")
        )
        parts.append(f'"{esc}"')
    if len(parts) == 1:
        return parts[0]
    return "\n    ".join(parts)


CRS_DATA_PREFIX = "@crs-data/"
CATALOG_MODE = "path-b"


def emit_catalog(assets: list[tuple[str, str]], mode: str, out_cc: Path, out_h: Path) -> None:
    out_cc.parent.mkdir(parents=True, exist_ok=True)
    entries = []
    body = [
        "// Generated by scripts/generate_rules_catalog.py — do not edit.",
        f"// catalog_mode={mode}",
        '#include "generated/rules_catalog.h"',
        "#include <cstring>",
        "namespace modsecurity_proxy_wasm_rules {",
        "namespace {",
    ]
    for idx, (virtual_path, content) in enumerate(assets):
        sym = f"kAsset_{idx}"
        lit = raw_cpp_string(content, sym)
        body.append(f"static const char {sym}[] =\n    {lit};")
        entries.append(
            f'  {{"{virtual_path}", {sym}, sizeof({sym}) - 1}},'
        )
    body.append("static const RuleAsset kCatalog[] = {")
    body.extend(entries)
    body.append("};")
    body.append("static const size_t kCatalogSize = sizeof(kCatalog) / sizeof(kCatalog[0]);")
    body.append(f'static const char kCatalogMode[] = "{mode}";')
    body.append("}  // namespace")
    body.append("")
    body.append("const char* catalog_mode() { return kCatalogMode; }")
    body.append("")
    body.append("const RuleAsset* lookup(const char* path) {")
    body.append("  if (path == nullptr) return nullptr;")
    body.append("  for (size_t i = 0; i < kCatalogSize; ++i) {")
    body.append("    if (std::strcmp(kCatalog[i].path, path) == 0) return &kCatalog[i];")
    body.append("  }")
    body.append("  return nullptr;")
    body.append("}")
    body.append("")
    body.append("void foreach_owasp_crs(bool (*fn)(const RuleAsset&, void*), void* user) {")
    body.append("  if (fn == nullptr) return;")
    body.append("  for (size_t i = 0; i < kCatalogSize; ++i) {")
    body.append('    const char* p = kCatalog[i].path;')
    body.append('    if (std::strncmp(p, "@owasp_crs/", 11) != 0) continue;')
    body.append("    if (!fn(kCatalog[i], user)) return;")
    body.append("  }")
    body.append("}")
    body.append("")
    body.append("void foreach_crs_data_file(bool (*fn)(const RuleAsset&, void*), void* user) {")
    body.append("  if (fn == nullptr) return;")
    body.append(f'  static const char kDataPrefix[] = "{CRS_DATA_PREFIX}";')
    body.append("  const size_t prefix_len = sizeof(kDataPrefix) - 1;")
    body.append("  for (size_t i = 0; i < kCatalogSize; ++i) {")
    body.append("    const char* p = kCatalog[i].path;")
    body.append("    if (std::strncmp(p, kDataPrefix, prefix_len) != 0) continue;")
    body.append("    if (!fn(kCatalog[i], user)) return;")
    body.append("  }")
    body.append("}")
    body.append("")
    body.append("}  // namespace modsecurity_proxy_wasm_rules")
    out_cc.write_text("\n".join(body) + "\n", encoding="utf-8")

    out_h.write_text(
        """// Generated by scripts/generate_rules_catalog.py — do not edit.
#ifndef MODSECURITY_PROXY_WASM_GENERATED_RULES_CATALOG_H_
#define MODSECURITY_PROXY_WASM_GENERATED_RULES_CATALOG_H_

#include <cstddef>

namespace modsecurity_proxy_wasm_rules {

struct RuleAsset {
  const char* path;
  const char* data;
  std::size_t size;
};

// Always "path-b": helpers + @crs-data only (no @owasp_crs / @crs-setup-conf).
const char* catalog_mode();
const RuleAsset* lookup(const char* path);
void foreach_owasp_crs(bool (*fn)(const RuleAsset&, void*), void* user);
void foreach_crs_data_file(bool (*fn)(const RuleAsset&, void*), void* user);

}  // namespace modsecurity_proxy_wasm_rules

#endif
""",
        encoding="utf-8",
    )


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--crs", type=Path, required=True, help="coreruleset checkout")
    ap.add_argument("--demo", type=Path, required=True, help="demo-conf.conf")
    ap.add_argument("--ftw", type=Path, required=True, help="ftw-config.conf")
    ap.add_argument(
        "--kubewaf-defaults",
        type=Path,
        required=False,
        default=None,
        help="kubewaf-defaults.conf (production baseline for kubeWAF)",
    )
    ap.add_argument(
        "--mode",
        choices=(CATALOG_MODE,),
        default=CATALOG_MODE,
        help="Catalog mode (path-b only).",
    )
    ap.add_argument("--out-cc", type=Path, default=Path("src/generated/rules_catalog.cc"))
    ap.add_argument("--out-h", type=Path, default=Path("src/generated/rules_catalog.h"))
    args = ap.parse_args()

    if args.mode != CATALOG_MODE:
        print(
            f"ERROR: only catalog mode {CATALOG_MODE!r} is supported (got {args.mode!r})",
            file=sys.stderr,
        )
        return 1

    crs = args.crs
    rules_dir = crs / "rules"
    if not rules_dir.is_dir():
        print(f"ERROR: missing {rules_dir}", file=sys.stderr)
        return 1

    assets: list[tuple[str, str]] = []
    assets.append(("@demo-conf", args.demo.read_text(encoding="utf-8", errors="replace")))
    assets.append(("@ftw-conf", args.ftw.read_text(encoding="utf-8", errors="replace")))
    kubewaf_defaults = args.kubewaf_defaults
    if kubewaf_defaults is None:
        kubewaf_defaults = args.demo.parent / "kubewaf-defaults.conf"
    if kubewaf_defaults.is_file():
        assets.append(
            ("@kubewaf-defaults", kubewaf_defaults.read_text(encoding="utf-8", errors="replace"))
        )

    data_files = sorted(rules_dir.glob("*.data"))
    if not data_files:
        print(f"ERROR: no *.data under {rules_dir} (required for @pmFromFile)", file=sys.stderr)
        return 1
    for path in data_files:
        virtual = f"{CRS_DATA_PREFIX}{path.name}"
        assets.append((virtual, path.read_text(encoding="utf-8", errors="replace")))

    emit_catalog(assets, CATALOG_MODE, args.out_cc, args.out_h)
    total = sum(len(c) for _, c in assets)
    print(
        f"Wrote {len(assets)} assets mode={CATALOG_MODE} "
        f"({len(data_files)} .data, 0 rule confs) "
        f"({total / 1024 / 1024:.2f} MiB) -> {args.out_cc}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
